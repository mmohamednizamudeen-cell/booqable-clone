// Generates replica/design/tokens.css from replica/design/tokens.json.
// Run after any token change (including the rebrand): node scripts/build-tokens.mjs
//
// Tailwind names: text roles drop the "text-" prefix so classes read naturally
// (text-ink, text-body, text-muted); border roles become "line" (border-line,
// border-line-input). Every other colour keeps its token name (bg-surface,
// bg-accent, text-on-accent, bg-success-pill).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "replica/design/tokens.json");
const out = join(root, "replica/design/tokens.css");
const t = JSON.parse(readFileSync(src, "utf8"));

const twColorName = (name) => {
  if (name === "text") return "ink";
  if (name.startsWith("text-")) return name.slice(5);
  if (name === "border") return "line";
  if (name.startsWith("border-")) return "line-" + name.slice(7);
  return name;
};

const px = (n) => `${n / 16}rem`;
const root_ = [];
const theme = [];

for (const [name, value] of Object.entries(t.color)) {
  root_.push(`  --c-${name}: ${value};`);
  theme.push(`  --color-${twColorName(name)}: var(--c-${name});`);
}

theme.push(`  --font-sans: ${t.font.sans};`);
theme.push(`  --font-mono: ${t.font.mono};`);

for (const [name, s] of Object.entries(t.type)) {
  theme.push(`  --text-${name}: ${px(s.size)};`);
  theme.push(`  --text-${name}--line-height: ${px(s.line)};`);
  theme.push(`  --text-${name}--font-weight: ${s.weight};`);
}

for (const [name, r] of Object.entries(t.radius)) {
  theme.push(`  --radius-${name}: ${r >= 999 ? "9999px" : px(r)};`);
}
for (const [name, s] of Object.entries(t.shadow)) {
  theme.push(`  --shadow-${name}: ${s};`);
}
theme.push(`  --ease-brand: ${t.motion.ease};`);
root_.push(`  --motion-fast: ${t.motion.fast};`);
root_.push(`  --motion-base: ${t.motion.base};`);

for (const [name, v] of Object.entries(t.layout)) {
  if (typeof v === "number") root_.push(`  --layout-${name}: ${px(v)};`);
}
for (const [name, v] of Object.entries(t.layout.breakpoints)) {
  theme.push(`  --breakpoint-${name}: ${px(v)};`);
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */

:root {
${root_.join("\n")}
}

@theme inline {
${theme.join("\n")}
}
`;

writeFileSync(out, css);
console.log(`wrote ${out}: ${Object.keys(t.color).length} colours, ${Object.keys(t.type).length} type steps`);
